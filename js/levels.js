// ----------------------------------------------------------------------------
//  WORLD - parsed level data
// ----------------------------------------------------------------------------
function parseLevel(raw) {
  const rows = raw.map.map(r => r.split(''));
  const h = rows.length;
  const w = Math.max(...rows.map(r => r.length));
  // pad
  rows.forEach(r => { while (r.length < w) r.push('.'); });
  return {
    ...raw,
    grid: rows,
    w, h,
    pixelW: w * TILE,
    pixelH: h * TILE,
  };
}
const LEVELS = RAW_LEVELS.map(parseLevel);

function triggerDecor(kind) {
  game.decorTriggered[kind] = true;
  game.decorTransition = 0;
  game.flashGold = 60;
  game.shake = 12;
  SFX.win();
  spawnPetals(W/2 + game.camera.x, 200 + game.camera.y);
  const msg = {
    lantern: "TOUTES LES LANTERNES S'ALLUMENT !",
    gear:    "L'USINE DEVIENT CAUCHEMAR MÉCANIQUE !",
    rose:    "LA LANDE SE COUVRE DE FLEURS !",
    brush:   "LE MONDE DEVIENT UN TABLEAU DE FRIDA !",
  }[kind];
  game.message = msg;
  game.messageTimer = 180;
  if (game.player) {
    showFloatText(msg, game.player.x + game.player.w/2, game.player.y - 30, '#f4d35e', 16);
  }
}


function loadLevel(idx) {
  game.levelIdx = idx;
  const raw = RAW_LEVELS[idx];
  game.level = parseLevel(raw);
  game.player = makePlayer(game.level.start);
  game.enemies = (raw.enemies || []).map(makeEnemy);
  game.pickups = buildPickups(game.level);
  game.camera.x = 0; game.camera.y = 0;
  game.particles = [];
  game.floatTexts = [];
  game.notifications = [];
  game.state = 'playing';
  game.bossKilled = false;
  game.message = '';
  game.shake = 0;
  // Reset per-level counters and decor flags
  game.collected = { tea:0, lantern:0, gear:0, rose:0, brush:0 };
  game.decorTriggered = { tea:false, lantern:false, gear:false, rose:false, brush:false };
  game.decorTransition = 0;
  // Apply selected power-up for the whole level
  const longDur = 60 * 999;
  const sp = game.selectedPower;
  const p = game.player;
  if (sp === 'ribbon')         p.powerDoubleJump = longDur;
  else if (sp === 'shawl')     p.powerSprint = longDur;
  else if (sp === 'crown')     p.powerInvinc = 60 * 30;
  else if (sp === 'fireball')  p.powerFireball = longDur;
  else if (sp === 'fly')       p.powerFly = longDur;
  else if (sp === 'magnet')    p.powerMagnet = longDur;
  else if (sp === 'slowmo')    p.powerSlowmo = longDur;
  else if (sp === 'scoreboost') p.powerScoreBoost = longDur;
  else if (sp === 'groundpound') p.powerGroundpound = longDur;
  else if (sp === 'brushcrea') { p.powerBrush = longDur; p.brushPlatesLeft = 3; }
  // Initial notification announcing the power
  if (sp) {
    const power = POWER_POOL.find(pp => pp.kind === sp);
    if (power) pushNotif({ iconKind: power.icon, title: power.name, desc: power.desc + (sp==='fireball'||sp==='brushcrea' ? '' : ''), color: power.color });
  }
  // Tutorial notif
  pushNotif({ iconKind:'tea', title: 'OBJECTIF', desc: 'Atteins le drapeau ! Collecte aussi les '+ ({lantern:'lanternes',gear:'engrenages',rose:'roses',brush:'pinceaux'}[LEVEL_THEME_OBJECT[idx]] || 'objets'), color: '#f4d35e' });
  game.projectiles = [];
}


